// Minimal ASCII DXF writer for the generated samples (HEADER, TABLES with layers, BLOCKS, ENTITIES).
// Coordinates are written as given; the caller converts meters to drawing units.

export interface P {
  x: number;
  y: number;
}

const f = (n: number) => (Math.abs(n) < 1e-9 ? '0.0' : Number(n.toFixed(4)).toString());

class Out {
  lines: string[] = [];
  g(code: number, value: string | number): this {
    this.lines.push(String(code), typeof value === 'number' ? f(value) : value);
    return this;
  }
}

export class EntityWriter {
  constructor(
    protected o: Out,
    protected handle: () => string,
  ) {}

  protected head(type: string, layer: string, sub: string): void {
    this.o.g(0, type).g(5, this.handle()).g(100, 'AcDbEntity').g(8, layer).g(100, sub);
  }

  line(layer: string, a: P, b: P): this {
    this.head('LINE', layer, 'AcDbLine');
    this.o.g(10, a.x).g(20, a.y).g(30, 0).g(11, b.x).g(21, b.y).g(31, 0);
    return this;
  }

  polyline(layer: string, pts: P[], closed = false): this {
    this.head('LWPOLYLINE', layer, 'AcDbPolyline');
    this.o.g(90, String(pts.length)).g(70, closed ? '1' : '0');
    for (const p of pts) this.o.g(10, p.x).g(20, p.y);
    return this;
  }

  /** Angles in degrees, counterclockwise from a0 to a1. */
  arc(layer: string, c: P, r: number, a0: number, a1: number): this {
    this.head('ARC', layer, 'AcDbCircle');
    this.o.g(10, c.x).g(20, c.y).g(30, 0).g(40, r).g(100, 'AcDbArc').g(50, a0).g(51, a1);
    return this;
  }

  circle(layer: string, c: P, r: number): this {
    this.head('CIRCLE', layer, 'AcDbCircle');
    this.o.g(10, c.x).g(20, c.y).g(30, 0).g(40, r);
    return this;
  }

  text(layer: string, p: P, height: number, text: string, centered = true): this {
    this.head('TEXT', layer, 'AcDbText');
    this.o.g(10, p.x).g(20, p.y).g(30, 0).g(40, height).g(1, text);
    if (centered) this.o.g(72, '1').g(11, p.x).g(21, p.y).g(31, 0);
    this.o.g(100, 'AcDbText');
    if (centered) this.o.g(73, '2');
    return this;
  }

  mtext(layer: string, p: P, height: number, text: string): this {
    this.head('MTEXT', layer, 'AcDbMText');
    this.o.g(10, p.x).g(20, p.y).g(30, 0).g(40, height).g(71, '5').g(1, text);
    return this;
  }

  insert(layer: string, name: string, p: P, rotationDeg = 0, sx = 1, sy = 1): this {
    this.head('INSERT', layer, 'AcDbBlockReference');
    this.o.g(2, name).g(10, p.x).g(20, p.y).g(30, 0);
    if (sx !== 1) this.o.g(41, sx);
    if (sy !== 1) this.o.g(42, sy);
    if (rotationDeg) this.o.g(50, rotationDeg);
    return this;
  }
}

export interface WriterOptions {
  version: string;
  insunits: number;
  codepage: string;
}

export class DxfWriter extends EntityWriter {
  private layers = new Map<string, number>();
  private blocks: { name: string; body: string[] }[] = [];
  private entities = new Out();
  private n = 0x100;

  constructor(private opts: WriterOptions) {
    const out = new Out();
    super(out, () => '');
    this.o = this.entities;
    this.handle = () => (this.n++).toString(16).toUpperCase();
  }

  layer(name: string, color = 7): this {
    if (!this.layers.has(name)) this.layers.set(name, color);
    return this;
  }

  block(name: string, draw: (w: EntityWriter) => void): this {
    if (this.blocks.some((b) => b.name === name)) return this;
    const out = new Out();
    draw(new EntityWriter(out, () => (this.n++).toString(16).toUpperCase()));
    this.blocks.push({ name, body: out.lines });
    return this;
  }

  hasBlock(name: string): boolean {
    return this.blocks.some((b) => b.name === name);
  }

  override toString(): string {
    const o = new Out();
    o.g(999, 'CAD Tour sample generated by scripts/make-samples.ts');
    o.g(0, 'SECTION').g(2, 'HEADER');
    o.g(9, '$ACADVER').g(1, this.opts.version);
    o.g(9, '$DWGCODEPAGE').g(3, this.opts.codepage);
    o.g(9, '$INSUNITS').g(70, String(this.opts.insunits));
    o.g(9, '$HANDSEED').g(5, (this.n + 0x100).toString(16).toUpperCase());
    o.g(0, 'ENDSEC');
    o.g(0, 'SECTION').g(2, 'TABLES');
    o.g(0, 'TABLE').g(2, 'LTYPE').g(5, '5').g(100, 'AcDbSymbolTable').g(70, '1');
    o.g(0, 'LTYPE').g(5, '14').g(100, 'AcDbSymbolTableRecord').g(100, 'AcDbLinetypeTableRecord').g(2, 'CONTINUOUS').g(70, '0').g(3, 'Solid line').g(72, '65').g(73, '0').g(40, 0);
    o.g(0, 'ENDTAB');
    o.g(0, 'TABLE').g(2, 'LAYER').g(5, '2').g(100, 'AcDbSymbolTable').g(70, String(this.layers.size + 1));
    for (const [name, color] of [['0', 7] as [string, number], ...this.layers]) {
      o.g(0, 'LAYER').g(5, (this.n++).toString(16).toUpperCase()).g(100, 'AcDbSymbolTableRecord').g(100, 'AcDbLayerTableRecord').g(2, name).g(70, '0').g(62, String(color)).g(6, 'CONTINUOUS');
    }
    o.g(0, 'ENDTAB');
    o.g(0, 'ENDSEC');
    o.g(0, 'SECTION').g(2, 'BLOCKS');
    for (const b of this.blocks) {
      o.g(0, 'BLOCK').g(5, (this.n++).toString(16).toUpperCase()).g(100, 'AcDbEntity').g(8, '0').g(100, 'AcDbBlockBegin').g(2, b.name).g(70, '0').g(10, 0).g(20, 0).g(30, 0).g(3, b.name).g(1, '');
      o.lines.push(...b.body);
      o.g(0, 'ENDBLK').g(5, (this.n++).toString(16).toUpperCase()).g(100, 'AcDbEntity').g(8, '0').g(100, 'AcDbBlockEnd');
    }
    o.g(0, 'ENDSEC');
    o.g(0, 'SECTION').g(2, 'ENTITIES');
    o.lines.push(...this.entities.lines);
    o.g(0, 'ENDSEC');
    o.g(0, 'EOF');
    return o.lines.join('\r\n') + '\r\n';
  }
}

/** Encodes text in a single-byte Windows code page (for legacy DXF samples). */
export function encodeCodepage(text: string, label: string): Uint8Array {
  const dec = new TextDecoder(label);
  const map = new Map<string, number>();
  for (let b = 0; b < 256; b++) {
    const ch = dec.decode(new Uint8Array([b]));
    if (!map.has(ch)) map.set(ch, b);
  }
  const out: number[] = [];
  for (const ch of text) {
    const b = map.get(ch);
    if (b === undefined) throw new Error(`Character ${ch} is not in ${label}`);
    out.push(b);
  }
  return new Uint8Array(out);
}
